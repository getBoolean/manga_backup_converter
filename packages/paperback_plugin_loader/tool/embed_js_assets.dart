// Regenerates `lib/src/host/js_assets.g.dart` from `assets/*.js`.
//
//     dart run tool/embed_js_assets.dart          (from packages/paperback_plugin_loader)
//
// The worker ships as an AOT executable that cannot read package files, so
// the host JavaScript is compiled in as string constants. Each constant's
// SHA-256 is recorded beside it so a test can prove the embedded text is the
// committed asset.
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';

const Map<String, String> _assets = <String, String>{
  'prelude.js': 'preludeJs',
  'api08.js': 'api08Js',
  'api09.js': 'api09Js',
  'ops.js': 'opsJs',
  'paperback_host_lib.js': 'hostLibJs',
};

void main() {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/embed_js_assets.dart from assets/*.js. Do not edit.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln('/// Host JavaScript embedded for the AOT worker (see `assets/`).')
    ..writeln('library;')
    ..writeln();
  final digests = <String, String>{};
  for (final MapEntry<String, String> e in _assets.entries) {
    final String text = File('assets/${e.key}').readAsStringSync().replaceAll('\r\n', '\n');
    digests[e.key] = sha256.convert(utf8.encode(text)).toString();
    out
      ..writeln('/// `assets/${e.key}`')
      ..writeln('const String ${e.value} = ${_literal(text)};')
      ..writeln();
  }
  out.writeln('/// SHA-256 of each embedded asset (LF line endings).');
  out.writeln('const Map<String, String> embeddedAssetSha256 = <String, String>{');
  digests.forEach((String k, String v) => out.writeln("  '$k': '$v',"));
  out.writeln('};');
  File('lib/src/host/js_assets.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('Wrote lib/src/host/js_assets.g.dart (${digests.length} assets)');
}

/// A Dart expression for [text]: raw triple-quoted chunks, with any `'''`
/// in the text emitted as a separate ordinary literal.
String _literal(String text) {
  final pieces = <String>[];
  for (final String part in text.split("'''")) {
    // A raw triple-quoted string cannot end in a quote; move trailing quotes
    // (at most two, since the text was split on three) into their own literal.
    final String body = part.replaceFirst(RegExp(r"'+$"), '');
    final String quotes = part.substring(body.length);
    pieces.add("r'''$body'''");
    if (quotes.isNotEmpty) pieces.add('"$quotes"');
    pieces.add("\"'''\"");
  }
  pieces.removeLast();
  return pieces.join(' ');
}
