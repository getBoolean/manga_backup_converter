// Embeds the committed Aidoku qualification fixtures into a Dart file so the
// U13 device test (integration_test/source_runners_android_test.dart) can
// replay them on Android, where the repository's files are not reachable.
//
// Nothing is downloaded: the inputs are the committed `.aix` artifacts and
// captures. Only the exchanges the device cases replay are kept (the full
// MangaDex capture also covers home, listings and pages).
//
// Usage (from the repository root):
//   dart run tool/generate_android_aidoku_fixtures.dart          # write
//   dart run tool/generate_android_aidoku_fixtures.dart --check  # verify
//
// `--check` fails when the generated file differs from what the committed
// fixtures produce (stale bundle, or edited fixture bytes).
//
// Follow-up: a debug-only Gradle asset set in packages/source_runtime_android
// (as U17 does for its Tachi APK) would carry these files without a
// generated Dart file.
import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

const String _out = 'integration_test/aidoku_fixture_bundle.g.dart';
const String _aixDir = 'packages/aidoku_plugin_loader/test/aidoku/fixtures';
const String _captureRoot = 'fixtures/source_captures/aidoku';

/// Device cases: source → (artifact file, URL fragments of kept exchanges;
/// empty keeps every exchange).
const Map<String, (String, List<String>)> _sources =
    <String, (String, List<String>)>{
      'multi.mangadex': (
        'multi.mangadex-v12.aix',
        <String>['title=Onimai', '/manga/ed996855-70de-449f-bba2-e8e24224c14d'],
      ),
      'multi.mangafire': ('multi.mangafire-v8.aix', <String>[]),
      'en.weebcentral': ('en.weebcentral-v6.aix', <String>[]),
    };

String _generate() {
  final files = <String, List<int>>{};
  for (final MapEntry<String, (String, List<String>)> e in _sources.entries) {
    final (String aix, List<String> keep) = e.value;
    files['aix/$aix'] = File(p.join(_aixDir, aix)).readAsBytesSync();
    final String dir = p.join(_captureRoot, e.key);
    final manifest = jsonDecode(
      File(p.join(dir, 'capture.json')).readAsStringSync(),
    ) as Map<String, dynamic>;
    final List<dynamic> exchanges = (manifest['exchanges'] as List<dynamic>)
        .where((x) {
          if (keep.isEmpty) return true;
          final url =
              ((x as Map<String, dynamic>)['request']
                      as Map<String, dynamic>)['url']
                  as String;
          return keep.any(url.contains);
        })
        .toList();
    if (exchanges.isEmpty) throw StateError('No exchanges kept for ${e.key}');
    manifest['exchanges'] = exchanges;
    manifest['notes'] = 'Subset embedded for the U13 device test by tool/generate_android_aidoku_fixtures.dart';
    files['captures/${e.key}/capture.json'] = utf8.encode(
      const JsonEncoder.withIndent('  ').convert(manifest),
    );
    for (final dynamic x in exchanges) {
      final body =
          ((x as Map<String, dynamic>)['response']
                  as Map<String, dynamic>)['body']
              as String?;
      if (body != null) {
        files['captures/${e.key}/$body'] = File(p.join(dir, body))
            .readAsBytesSync();
      }
    }
  }
  final buffer = StringBuffer()
    ..writeln(
      '// GENERATED by tool/generate_android_aidoku_fixtures.dart. Do not edit.',
    )
    ..writeln(
      '// Committed Aidoku fixtures (pinned .aix artifacts and capture subsets)',
    )
    ..writeln(
      '// for integration_test/source_runners_android_test.dart. Provenance:',
    )
    ..writeln(
      '// fixtures/source_captures/aidoku/<source>/ (capture.json, artifact.json).',
    )
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln('/// Relative path → base64 file content.')
    ..writeln(
      'const Map<String, String> aidokuFixtureBundle = <String, String>{',
    );
  for (final String path in files.keys.toList()..sort()) {
    buffer.writeln("  '$path':");
    final String b64 = base64.encode(files[path]!);
    const chunk = 4000;
    for (var i = 0; i < b64.length; i += chunk) {
      final String part = b64.substring(
        i,
        i + chunk > b64.length ? b64.length : i + chunk,
      );
      buffer.writeln("      '$part'${i + chunk >= b64.length ? ',' : ''}");
    }
  }
  buffer.writeln('};');
  return buffer.toString();
}

void main(List<String> args) {
  final String generated = _generate();
  final file = File(_out);
  if (args.contains('--check')) {
    final String current = file.existsSync() ? file.readAsStringSync() : '';
    if (current != generated) {
      stderr.writeln(
        '$_out is stale; run dart run tool/generate_android_aidoku_fixtures.dart',
      );
      exitCode = 1;
      return;
    }
    stdout.writeln('$_out matches the committed fixtures.');
    return;
  }
  file.writeAsStringSync(generated);
  stdout.writeln('Wrote $_out (${generated.length} chars).');
}
